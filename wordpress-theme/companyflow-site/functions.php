<?php
/**
 * CompanyFlow Original WordPress wrapper.
 *
 * The React application remains the source of truth for the original design
 * and content. WordPress serves its built HTML, JS, CSS, and public media.
 */
if (!defined('ABSPATH')) { exit; }

add_action('after_setup_theme', function () {
    add_theme_support('title-tag');
    add_theme_support('post-thumbnails');
});

function cf_original_app_dir() {
    return trailingslashit(get_template_directory()) . 'app/';
}

add_filter('query_vars', function ($vars) {
    $vars[] = 'cf_original_asset';
    return $vars;
});

add_action('init', function () {
    add_rewrite_rule(
        '^(assets/.+|projects/.+|hero-team\\.webp|stressed-woman-laptop\\.webp|companyflow\\.svg|robots\\.txt|sitemap\\.xml)$',
        'index.php?cf_original_asset=$matches[1]',
        'top'
    );
});

add_action('after_switch_theme', function () {
    flush_rewrite_rules();
});

function cf_original_send_asset($relative) {
    $relative = ltrim(str_replace('\\\\', '/', (string) $relative), '/');
    if ($relative === '' || strpos($relative, '..') !== false) {
        status_header(400);
        exit;
    }
    $base = realpath(cf_original_app_dir());
    $file = realpath(cf_original_app_dir() . $relative);
    if (!$base || !$file || strpos($file, $base . DIRECTORY_SEPARATOR) !== 0 || !is_file($file)) {
        status_header(404);
        exit;
    }
    $types = array(
        'css' => 'text/css; charset=utf-8',
        'js' => 'application/javascript; charset=utf-8',
        'mjs' => 'application/javascript; charset=utf-8',
        'svg' => 'image/svg+xml',
        'webp' => 'image/webp',
        'png' => 'image/png',
        'jpg' => 'image/jpeg',
        'jpeg' => 'image/jpeg',
        'woff' => 'font/woff',
        'woff2' => 'font/woff2',
        'ico' => 'image/x-icon',
        'txt' => 'text/plain; charset=utf-8',
        'xml' => 'application/xml; charset=utf-8',
        'json' => 'application/json; charset=utf-8',
    );
    $ext = strtolower(pathinfo($file, PATHINFO_EXTENSION));
    header('Content-Type: ' . (isset($types[$ext]) ? $types[$ext] : 'application/octet-stream'));
    header('X-Content-Type-Options: nosniff');
    header('Cache-Control: public, max-age=86400');
    header('Content-Length: ' . filesize($file));
    readfile($file);
    exit;
}

function cf_original_render_app() {
    $asset = get_query_var('cf_original_asset');
    if ($asset) {
        cf_original_send_asset($asset);
    }

    if (is_admin() || (defined('REST_REQUEST') && REST_REQUEST)) {
        return;
    }
    $uri = isset($_SERVER['REQUEST_URI']) ? (string) $_SERVER['REQUEST_URI'] : '/';
    $path = parse_url($uri, PHP_URL_PATH);
    $path = '/' . ltrim((string) $path, '/');
    foreach (array('/wp-admin', '/wp-login.php', '/wp-json', '/wp-cron.php', '/xmlrpc.php') as $reserved) {
        if ($path === $reserved || strpos($path, $reserved . '/') === 0) {
            return;
        }
    }

    $app = cf_original_app_dir();
    $relative = trim(rawurldecode($path), '/');
    $candidate = $relative === '' ? $app . 'index.html' : $app . $relative . '/index.html';
    $candidateReal = realpath($candidate);
    $appReal = realpath($app);
    if (!$candidateReal || !$appReal || strpos($candidateReal, $appReal . DIRECTORY_SEPARATOR) !== 0 || !is_file($candidateReal)) {
        $candidate = $app . 'index.html';
    }
    if (!is_readable($candidate)) {
        status_header(503);
        echo 'CompanyFlow app files are missing. Install the complete CompanyFlow WordPress theme ZIP generated by GitHub Actions.';
        exit;
    }
    status_header(200);
    header('Content-Type: text/html; charset=utf-8');
    header('X-Content-Type-Options: nosniff');
    readfile($candidate);
    exit;
}
add_action('template_redirect', 'cf_original_render_app', 0);
